type builtinStudioURLRecord struct {
	Name string
	Host string
}

func builtinStudioURLProvider() studioMetadataProvider {
	return studioMetadataProvider{
		ID:   builtinStudioURLScraperID,
		Name: builtinStudioURLScraperName,
		Query: func(_ context.Context, candidate string) (*models.ScrapedStudio, error) {
			record, found := lookupBuiltinStudioURL(candidate)
			if !found {
				return nil, nil
			}
			return &models.ScrapedStudio{
				Name: record.Name,
				URLs: []string{"https://" + record.Host},
			}, nil
		},
	}
}

func lookupBuiltinStudioURL(candidate string) (builtinStudioURLRecord, bool) {
	if host, valid := normalizeStudioURLHost(candidate); valid {
		for {
			if name, found := builtinStudioNameByHost[host]; found {
				return builtinStudioURLRecord{Name: name, Host: host}, true
			}
			dot := strings.IndexByte(host, '.')
			if dot < 0 {
				break
			}
			host = host[dot+1:]
		}
	}

	key := metadata.NormalizeKey(candidate)
	if record, found := builtinStudioByName[key]; found {
		return record, true
	}
	record, found := builtinStudioByName[strings.ReplaceAll(key, " ", "")]
	return record, found
}

func normalizeStudioURLHost(raw string) (string, bool) {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return "", false
	}
	if !strings.Contains(raw, "://") {
		raw = "https://" + raw
	}
	parsed, err := url.Parse(raw)
	if err != nil || parsed.Hostname() == "" {
		return "", false
	}
	host := strings.TrimSuffix(strings.ToLower(parsed.Hostname()), ".")
	host = strings.TrimPrefix(host, "www.")
	return host, host != ""
}

// studioURLQueryVariants returns exact spellings worth querying against
// Stash-box's literal studio_urls.url filter. The most specific URL is tried
// first, followed by parent paths. HTTPS is required; both the original host
// and its registrable host are retained because Stash-box may store either.
func studioURLQueryVariants(raw string) []string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return nil
	}
	if !strings.Contains(raw, "://") {
		raw = "https://" + raw
	}
	parsed, err := url.Parse(raw)
	if err != nil || parsed.Hostname() == "" {
		return nil
	}

	host := strings.TrimSuffix(strings.ToLower(parsed.Hostname()), ".")
	hosts := []string{host}
	if registrable, err := publicsuffix.EffectiveTLDPlusOne(host); err == nil && registrable != host {
		hosts = append(hosts, registrable)
	} else if withoutWWW := strings.TrimPrefix(host, "www."); withoutWWW != host {
		hosts = append(hosts, withoutWWW)
	}

	path := parsed.EscapedPath()
	if unescaped, err := url.PathUnescape(path); err == nil {
		path = unescaped
	}
	path = "/" + strings.Trim(path, "/")
	if path == "/" {
		path = ""
	}

	var ret []string
	seen := make(map[string]struct{})
	appendVariant := func(host, path string) {
		base := "https://" + host + path
		for _, candidate := range []string{base + "/", base} {
			if _, duplicate := seen[candidate]; duplicate {
				continue
			}
			seen[candidate] = struct{}{}
			ret = append(ret, candidate)
		}
	}
	for {
		for _, candidateHost := range hosts {
			appendVariant(candidateHost, path)
		}
		if path == "" {
			break
		}
		if slash := strings.LastIndexByte(path, '/'); slash > 0 {
			path = path[:slash]
		} else {
			path = ""
		}
	}
	return ret
}

func studioNameCandidateFromURL(raw string) string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return ""
	}
	if !strings.Contains(raw, "://") {
		raw = "https://" + raw
	}
	parsed, err := url.Parse(raw)
	if err != nil || parsed.Hostname() == "" {
		return ""
	}
	host := strings.TrimSuffix(strings.ToLower(parsed.Hostname()), ".")
	if registrable, err := publicsuffix.EffectiveTLDPlusOne(host); err == nil {
		host = registrable
	}
	if dot := strings.IndexByte(host, '.'); dot >= 0 {
		host = host[:dot]
	}
	return strings.TrimSpace(host)
}

func studioCandidateURLMatches(candidate string, scrapedURLs []string) bool {
	candidateHost, valid := normalizeStudioURLHost(candidate)
	if !valid {
		return false
	}
	for _, raw := range scrapedURLs {
		host, valid := normalizeStudioURLHost(raw)
		if valid && (candidateHost == host || strings.HasSuffix(candidateHost, "."+host) || strings.HasSuffix(host, "."+candidateHost)) {
			return true
		}
	}
	return false
}

var builtinStudioByName = func() map[string]builtinStudioURLRecord {
	ret := make(map[string]builtinStudioURLRecord)
	ambiguous := make(map[string]struct{})
	for host, name := range builtinStudioNameByHost {
		record := builtinStudioURLRecord{Name: name, Host: host}
		keys := []string{metadata.NormalizeKey(name), strings.ReplaceAll(metadata.NormalizeKey(name), " ", "")}
		for _, key := range keys {
			if key == "" {
				continue
			}
			if current, found := ret[key]; found {
				if current.Name != name {
					ambiguous[key] = struct{}{}
				} else if current.Host < host {
					continue
				}
			}
			ret[key] = record
		}
	}
	for key := range ambiguous {
		delete(ret, key)
	}
	return ret
}()

